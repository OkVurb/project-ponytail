'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { root, inventory, isFeature } = require('./project');
function generate(base = root) {
  const modules = inventory(base).map(item => item.id).sort();
  const features = modules.filter(isFeature);
  const lua = '-- Generated by tools/gen-registry.js. Do not edit.\nreturn {\n' + features.map(id => `    ${JSON.stringify(id)},`).join('\n') + '\n};\n';
  fs.writeFileSync(path.join(base, 'src/features/manifest.lua'), lua);
  // Include the generated manifest even on the first build.
  if (!modules.includes('@src/features/manifest')) modules.push('@src/features/manifest');
  modules.sort();
  fs.writeFileSync(path.join(base, 'module-manifest.json'), JSON.stringify({ version: 1, modules }, null, 2) + '\n');
  return { modules: modules.length, features: features.length };
}
if (require.main === module) console.log('Generated registry:', generate());
module.exports = { generate };
